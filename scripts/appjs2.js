let n1 = prompt("Digite um número:");
n1 = Number(n1);
let n2 = prompt("Digite o numero: ");
n2 = Number(n2);
alert(`${n1} + ${n2} = ${n1 + n2}`);
alert(`${n1} - ${n2} = ${n1 - n2}`);
alert(`${n1} / ${n2} = ${n1 / n2}`);
alert(`${n1} % ${n2} = ${n1 % n2}`);
alert(`${n1} * ${n2} = ${n1 * n2}`);
alert(`${n1} ** ${n2} = ${n1 ** n2}`);
